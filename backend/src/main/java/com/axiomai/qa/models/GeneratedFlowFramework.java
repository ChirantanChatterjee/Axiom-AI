package com.axiomai.qa.models;

public class GeneratedFlowFramework {

    private String featureFile;

    private String pageObject;

    private String stepDefinitions;

    private String assertions;

    public GeneratedFlowFramework() {
    }

    public String getFeatureFile() {
        return featureFile;
    }

    public void setFeatureFile(String featureFile) {
        this.featureFile = featureFile;
    }

    public String getPageObject() {
        return pageObject;
    }

    public void setPageObject(String pageObject) {
        this.pageObject = pageObject;
    }

    public String getStepDefinitions() {
        return stepDefinitions;
    }

    public void setStepDefinitions(String stepDefinitions) {
        this.stepDefinitions = stepDefinitions;
    }

    public String getAssertions() {
        return assertions;
    }

    public void setAssertions(String assertions) {
        this.assertions = assertions;
    }
}